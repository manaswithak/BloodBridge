// Simplified red-cell donor matching rule for initial discovery only.
// Always have a licensed blood bank verify compatibility and eligibility.
const compatible = {
  'O-': ['O-'],
  'O+': ['O-', 'O+'],
  'A-': ['O-', 'A-'],
  'A+': ['O-', 'O+', 'A-', 'A+'],
  'B-': ['O-', 'B-'],
  'B+': ['O-', 'O+', 'B-', 'B+'],
  'AB-': ['O-', 'A-', 'B-', 'AB-'],
  'AB+': ['O-', 'O+', 'A-', 'A+', 'B-', 'B+', 'AB-', 'AB+']
};
export const donorGroupsFor = recipientGroup => compatible[recipientGroup] || [recipientGroup];
